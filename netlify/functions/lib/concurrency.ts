/**
 * Run `fn` over `items` with at most `limit` in flight. Results keep input
 * order. Used wherever a job fans out many small DB / API reads — a plain
 * Promise.all over hundreds of them trips rate limits and connection caps.
 */
export async function mapWithConcurrency<T, R>(
  items: T[],
  limit: number,
  fn: (item: T) => Promise<R>,
): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}
